namespace App\Tracker\Controller\Upload\Ajax;

use JTracker\Controller\AbstractAjaxController;

/**
 * Delete file controller class.
 *
 * @since  1.0
 */
class Delete extends AbstractAjaxController
{
    /**
     * Prepare the response.
     *
     * @return  mixed
     *
     * @since   1.0
     * @throws  \RuntimeException
     */
    protected function prepareResponse()
    {
        /** @var \JTracker\Application\Application $application */
        $application = $this->getContainer()->get('app');
        $user        = $application->getUser();

        if (!$user->id) {
            throw new \RuntimeException('You are not allowed to delete files.');
        }

        $file = $application->input->getCmd('file');

        if (!empty($file)) {
            // Only accept names as generated by the upload controller, no path components.
            if (!preg_match('/^[a-f0-9]{32}\.[a-z0-9]+$/', $file)) {
                throw new \RuntimeException('Invalid file name.');
            }

            $projectId = $application->getProject()->project_id;
            $session   = $application->getSession();
            $uploads   = (array) $session->get('tracker.uploads', []);
            $key       = array_search($projectId . '/' . $file, $uploads, true);

            // Users may only delete their own uploads from the current session, unless they are allowed to manage the project.
            if ($key === false && !$user->check('manage')) {
                throw new \RuntimeException('You are not allowed to delete this file.');
            }

            $path = JPATH_THEMES . '/' . $application->get('system.upload_dir') . '/' . $projectId . '/' . $file;

            if (!is_file($path)) {
                throw new \RuntimeException('File not found.');
            }

            try {
                unlink($path);
            } catch (\Exception $e) {
                throw new \RuntimeException($e->getMessage(), $e->getCode(), $e);
            }

            if ($key !== false) {
                unset($uploads[$key]);
                $session->set('tracker.uploads', array_values($uploads));
            }
        }
    }
}
